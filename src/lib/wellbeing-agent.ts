const TONE_MANNER: Record<RealtimeTonePreset, string> = {
  calm: "落ち着いた、ていねいな話し言葉で。テンポはゆっくりめ、語尾は穏やかに。",
  bright: "少し軽快で前向きな話し言葉で。テンポよく、相づちや受けを明るめに。",
  soft: "やわらかく親しみのある話し言葉で。角のない言い回しで、寄り添うように。",
  firm: "きっちりめで芯のある話し言葉で。ただし堅すぎず、言い切りは明瞭に。",
};

function buildToneMannerInstruction(tone: RealtimeTonePreset): string {
  return `${TONE_MANNER[tone]}
- ただし「です・ます」の丁寧さと、上の「文の組み立てとつなぎ」のルールは必ず土台にする。口調の調整はその範囲で行う。`;
}

export interface WellbeingAgentOptions {
  skeletonInstructions?: string;
  styleInstructions?: string;
  tone?: RealtimeTonePreset;
  editorialController?: EditorialController;
}

export function buildWellbeingAgent({
  skeletonInstructions,
  styleInstructions,
  tone,
  editorialController,
}: WellbeingAgentOptions = {}): RealtimeAgent<RealtimeSessionStyleContext> {
  const sections = [baseInstructions];

  if (skeletonInstructions && skeletonInstructions.trim()) {
    sections.push(
      `## 頭の中の地図（事前リサーチ・会話中ずっと活用する）\n${skeletonInstructions.trim()}`
    );
  }

  if (tone) {
    sections.push(`## このセッションの口調\n${buildToneMannerInstruction(tone)}`);
  }

  if (styleInstructions && styleInstructions.trim()) {
    sections.push(`## 話し方の指定（最優先）\n${styleInstructions.trim()}`);
  }

  return new RealtimeAgent<RealtimeSessionStyleContext>({
    name: "WellbeingInterviewer",
    instructions: sections.join("\n\n"),
    tools: [createNoteInterviewFocusTool(editorialController)],
  });
}
